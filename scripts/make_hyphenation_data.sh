#!/usr/bin/env bash
# Vendor the Knuth–Liang hyphenation dictionaries this engine bakes into the
# compiled library (issue #158) into src/i18n/data/hyph/.
#
# The `hyphenation` crate ships every hyph-utf8 pattern set as a prebuilt
# `dictionaries/<code>.standard.bincode` inside its crate tarball — 82 files,
# ~2.8 MB — and offers an `embed_all` feature that compiles all of them into
# the binary. That is the wheel-size risk issue #124 names by name, so the
# crate is depended on with `default-features = false` (no embedding, no
# build-time dictionary generation) and this script copies only the few
# dictionaries a `w:lang` tag in the corpus actually reaches, out of the
# *pinned* crate source in Cargo's registry and into the tree, where
# `src/i18n/hyphenate.rs` `include_bytes!`s them. Same shape as
# scripts/make_icu_data.sh: committed data, regenerated by a script whose
# list is the single source of truth, no Cargo feature gate.
#
# The `.bincode` files are serialized with the crate's own `bincode 1.x`
# schema for `hyphenation_commons::dictionary::Standard`, so they are tied to
# the exact crate version Cargo.toml pins (`=0.8.4`). Bumping that version
# means re-running this script and committing the diff.
#
# LANGUAGES is the single source of truth for the vendored set — don't
# duplicate it elsewhere. The codes are the crate's own (`Language::code()`),
# which are *not* plain BCP-47: German is `de-1996` (reformed orthography),
# and the only Swiss set the crate has is `de-ch-1901` (traditional
# orthography), which is why `HyphenLanguage::from_tag` maps every `de-*`
# tag to `de-1996` rather than offering a Swiss variant. The set is the three
# languages the corpus and the issue name (en-US, en-GB, ru) plus de-1996 for
# the fixture, whose long compounds make hyphenation visible in a narrow
# column. Extend it here, in one place, when a fixture and a real caller
# justify a language — the rule make_icu_data.sh already applies.
#
# Sizes, raw, as copied (bincode over an `fst` automaton; measured here):
#
#   de-1996.standard.bincode   204,040
#   en-us.standard.bincode      90,932
#   en-gb.standard.bincode      48,093
#   ru.standard.bincode         42,531
#   total                      385,596
#
# For scale: the four `.bincode` files deflate to 214,624 bytes (56%), which is
# the order of the #130 LSTM addition (+331 KB on the wheel) rather than the
# CLDR text tables (#128/#129) that deflate to a quarter. The wheel delta
# itself was *not* measured for this change — the branch was built in an
# environment where a release build was off limits — so the Cargo.toml
# comment records the raw and deflated figures and leaves the wheel number
# to be filled in by the first release build that carries this.
#
# Usage:
#
#     cargo fetch                     # the pinned crate must be in the registry
#     scripts/make_hyphenation_data.sh
#
# Regenerate and commit the result whenever LANGUAGES or the pinned crate
# version changes. The copy is byte-exact — commit the diff, don't hand-edit.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

LANGUAGES="de-1996 en-us en-gb ru"

# The crate version Cargo.toml pins. Read it back rather than restating it,
# so the two cannot drift.
VERSION=$(grep -E '^hyphenation = \{ version = "=' Cargo.toml | sed -E 's/.*version = "=([^"]+)".*/\1/')
if [ -z "$VERSION" ]; then
  echo "could not read the pinned hyphenation version from Cargo.toml" >&2
  exit 1
fi

# Cargo's registry source checkout for the pinned crate. `cargo fetch` puts it
# there; the glob covers the per-index directory name.
SRC=$(ls -d "${CARGO_HOME:-$HOME/.cargo}"/registry/src/*/hyphenation-"$VERSION" 2>/dev/null | head -n 1)
if [ -z "$SRC" ]; then
  echo "hyphenation-$VERSION is not in the Cargo registry; run \`cargo fetch\` first" >&2
  exit 1
fi

OUT=src/i18n/data/hyph
mkdir -p "$OUT"
for lang in $LANGUAGES; do
  file="$lang.standard.bincode"
  cp "$SRC/dictionaries/$file" "$OUT/$file"
  printf '%-28s %9d bytes\n' "$file" "$(wc -c < "$OUT/$file")"
done
